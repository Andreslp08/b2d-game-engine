import { GameObject } from "@b2d-engine/core/common/entities/game-object";
import Vector2 from "@b2d-engine/core/math/vector2";
import { Collider } from "@b2d-engine/core/physics/components/collider";
import { PlayerMovement } from "../script-components/player/player-movement";
import { PlayerController } from "../script-components/player/player-controller";
import { PlayerCameraController } from "../script-components/player/player-camera-controller";
import { HealthComponent } from "../script-components/shared/health-component";
import { FallDamage } from "../script-components/player/fall-damage";
import { PlayerHud } from "../hud/hud";
import { ShieldComponent } from "../script-components/shared/shield-component";
import { WeaponHolder } from "../script-components/weapon/weapon";
import { DynamicBody } from "@b2d-engine/core/physics/components/dynamic-body";
import { PlayerSpriteController } from "../script-components/player/sprite-controller";
import { QuickSlotInputController } from "../script-components/player/quick-slot-input-controller";
import { PlayerLifeController } from "../script-components/player/player-life-controller";
import { PlayerAidKitController } from "../script-components/player/player-aid-kit-controller";
import { HealingFlashEffect } from "../script-components/shared/healing-flash-effect";
import { DamageFlashEffect } from "../script-components/shared/damage-flash-effect";
import { AimingController } from "../script-components/player/aiming-controller";
import { PlayerAimingArm } from "../script-components/player/player-aiming-arm";
import { PlayerSkin } from "../config/constants";
import { PlayerSkinComponent } from "../script-components/player/player-skin-component";
import { itemRegistry } from "../items/item-catalog";
import { InventoryComponent } from "../items/components/inventory-component";
import { QuickSlotsComponent } from "../items/components/quick-slots-component";
import { EquipmentComponent } from "../items/components/equipment-component";
import { Sprite } from "@b2d-engine/core/graphics/sprites/components/sprite";
import { TriggerArea } from "@b2d-engine/core/trigger-area";
import { Culling, CullingConfigComponent } from "@b2d-engine/core/performance/culling";
import { CullingType } from "@b2d-engine/core/performance/enum/culling-type";
import { createWeapon } from "./weapon";
import type { Scene } from "@b2d-engine/core/scenes/scene";
import { PlayerZIndexManager } from "../script-components/player/player-zindex";
import { PlayerInputController } from "../script-components/player/player-input-controller";

type Params = {
	scene: Scene;
	position: Vector2;
	skin?: PlayerSkin;
};
export const createPlayer = (params: Params): GameObject => {
	const { position, skin = PlayerSkin.SKIN1, scene } = params;
	const entity = new GameObject({
		position: position,
		rotation: 0,
		size: new Vector2(0.8, 1.8),
	});
	entity.addTag("player");
	entity.addComponent(new PlayerSkinComponent(skin));
	entity.addComponent(new PlayerSpriteController());
	entity.addComponent(new DynamicBody());
	entity.addComponent(new Collider(new Vector2(0, 0), new Vector2(0.5, 1)));
	const cullingConfig = entity.getComponent(CullingConfigComponent);
	if (cullingConfig) cullingConfig.cullingType = CullingType.NONE;
	const triggerArea = new TriggerArea(new Vector2(0, 0), new Vector2(0.5, 1.7));
	entity.addComponent(triggerArea);
	entity.addComponent(new PlayerMovement());
	entity.addComponent(new PlayerInputController());
	entity.addComponent(new PlayerController());
	entity.addComponent(new PlayerCameraController());
	entity.addComponent(new HealthComponent(100, 100, false));
	entity.addComponent(new ShieldComponent());
	entity.addComponent(new FallDamage());
	entity.addComponent(new PlayerHud());
	entity.addComponent(new PlayerLifeController());
	const playerAimingArm = new PlayerAimingArm(skin);
	entity.addComponent(playerAimingArm);
	entity.addComponent(new QuickSlotInputController());
	entity.addComponent(new AimingController());
	entity.addComponent(new WeaponHolder());
	const weapon = createWeapon(Vector2.ZERO.clone());
	scene.addEntity(weapon);
	entity.getComponent(WeaponHolder).attachWeapon(weapon);
	const inventoryComponent = new InventoryComponent(itemRegistry);
	const quickSlots = new QuickSlotsComponent();
	const zIndexManager = new PlayerZIndexManager();
	entity.addComponent(zIndexManager);
	quickSlots.set(0, null);
	entity.addComponent(inventoryComponent);
	entity.addComponent(quickSlots);
	const equipment = new EquipmentComponent();
	entity.addComponent(equipment);
	entity.addComponent(new HealingFlashEffect());
	const damageFlashEffect = new DamageFlashEffect();
	damageFlashEffect.setAdditionalSpritesProvider(() => {
		const armSprite = playerAimingArm.getArm()?.getComponent(Sprite);
		return armSprite ? [armSprite] : [];
	});
	entity.addComponent(damageFlashEffect);
	entity.addComponent(new PlayerAidKitController());
	const collider = entity.getComponent(Collider);
	const playerBody = entity.getComponent(DynamicBody);
	const playerMovement = entity.getComponent(PlayerMovement);
	playerMovement.direction.x = 1;
	collider.setSize(new Vector2(0.5, entity.transform.size.y * 0.95));
	collider.setOffsetPosition(new Vector2(0, 0));
	playerBody.gravity = 60;
	playerBody.mass = 80;
	playerBody.friction = 1800;
	playerBody.dragScale = 109;
	playerMovement.forceX = 14000;
	playerMovement.forceY = 16000;
	playerMovement.maxJumpHeight = 1.2;
	playerMovement.dashForceX = 17000;
	playerMovement.dashMaxSpeedX = 13;
	playerMovement.dashDuration = 0.16;
	playerMovement.dashCooldown = 0.45;
	playerBody.bounciness = new Vector2(0, 0);
	return entity;
};
